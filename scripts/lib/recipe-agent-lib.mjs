// =============================================================================
// recipe-agent-lib.mjs - rendering a recipe into a reasoning subagent, as a pure lib.
//
// what-it-is:   the transform from a _workflows/<name>.md recipe to an agents/<name>.md subagent,
//               plus the allowlist of which recipes get one.
// what-it-does: renderAgent(name, recipeMarkdown, plugin) -> the exact subagent file contents.
// why:          SPEC-09 phase 3 (C3-3). A recipe run inline drops every intermediate artifact into
//               the caller's conversation when the caller wants the last one. A subagent runs the
//               same chain in its own context and returns only the composite artifact. Generating
//               it from the same _workflows/ source as the command keeps the chain in one place:
//               two hand-kept copies of a procedure is the drift class this repo gates against.
// used-by:      scripts/gen-recipe-commands.mjs; tests/recipe-agent-lib.test.mjs
//
// The selection criterion is written down in docs/internal/AUTHORING.md ("Reasoning subagents")
// and the evidence behind it in docs/internal/experiments/2026-09-15-subagent-suitability-inventory.md.
// Read those before adding a name here: the per-skill `subagent_suitable` field was authored
// against no written rule and ended up selecting nothing, and this list must not repeat that.
// =============================================================================

import { frontmatterBlock, scalar, stepNames, bodyAfterTitle } from './recipe-command-lib.mjs';

/**
 * The recipes that ship as subagents, each with the reason it qualifies. Not every recipe should:
 * a subagent earns its place only when the caller wants the deliverable without the derivation,
 * and the chain can finish in one sitting. The rationale is part of the entry so the next person
 * does not re-derive it.
 */
export const SUBAGENT_RECIPES = Object.freeze({
  'think-stress-test-decision':
    'The longest chain (4 required steps, the only recipe above 3), so it drops the most intermediate '
    + 'artifacts a caller will not reread. The decision brief it ends on is self-contained.',
  'think-audit-reasoning':
    'Chosen from the 3-step tie on mechanism, not size: an auditor running in the caller\'s context '
    + 'shares the unstated assumptions of the reasoning it audits. A subagent starts without that '
    + 'conversation, so it can judge only what is on the page, which is what an evidence-versus-inference '
    + 'audit is supposed to do.',
});

/**
 * Read-only, and the grant IS the constraint (the C4-6 pattern: hard limits in the tools field, not
 * prose prohibitions on a broad grant). Read is required, not optional: every step's SKILL.md points
 * at its own references/TEMPLATE.md and EXAMPLE.md, which preloading does not inject.
 */
export const AGENT_TOOLS = 'Read, Glob, Grep';

export const GENERATED_BY = 'scripts/gen-recipe-commands.mjs';

/** True when an agent file's contents carry this generator's marker, i.e. the generator owns it. */
export function isGeneratedAgent(contents) {
  return String(contents || '').includes(`<!-- GENERATED by ${GENERATED_BY} from _workflows/`);
}

/**
 * The composite artifact's noun phrase, from the recipe's "Composite artifact: a decision brief -
 * ..." line. Throws rather than guessing: the subagent's whole contract is "return only this", so a
 * recipe whose artifact cannot be named cannot be wrapped.
 */
export function compositeArtifact(body) {
  const m = String(body || '').match(/^Composite artifact:\s*(an?\s+[^.,:;\n]+?)\s*(?:\s-\s|[.,:;]|$)/m);
  if (!m) throw new Error('recipe has no parsable "Composite artifact: a/an <noun> ..." line');
  return m[1].trim();
}

/**
 * Numbered chain steps that name no skill: a step that happens in the world, not in the chain
 * (think-pdca-a3's "Do - run the change in the world"). A delegate returns once, so it cannot wait
 * across such a gap; a recipe that has one cannot be wrapped, whatever its length.
 */
export function worldSteps(body) {
  return (String(body || '').match(/^\d+\.\s+.*$/gm) || []).filter((l) => !/^\d+\.\s+`think-/.test(l));
}

/** "a decision brief" -> "decision brief". */
function withoutArticle(phrase) {
  return phrase.replace(/^an?\s+/, '');
}

/** Render one recipe into its subagent file contents. Deterministic: same input, same bytes. */
export function renderAgent(name, recipeMd, plugin) {
  if (!plugin) throw new Error('renderAgent needs the plugin name, to namespace the preloaded skills');
  const { fm, body } = frontmatterBlock(recipeMd);
  const description = scalar(fm, 'description') || '';
  const steps = stepNames(fm);
  if (steps.length < 2) throw new Error(`${name}: a recipe subagent needs a chain of at least 2 steps`);
  const gaps = worldSteps(body);
  if (gaps.length) {
    throw new Error(`${name}: ${gaps.length} chain step(s) name no skill (a real-world gap a one-shot delegate cannot span): ${gaps[0]}`);
  }
  const artifact = compositeArtifact(body);
  const noun = withoutArticle(artifact);
  const n = steps.length;
  const authored = bodyAfterTitle(body);
  const skillsYaml = steps.map((s) => `  - ${plugin}:${s}`).join('\n');
  const skillsList = steps.map((s) => `\`${s}\``).join(', ');

  return `---
name: ${name}
description: ${description} Runs the ${n}-skill ${name} chain in its own context and returns only the finished ${noun}, so the intermediate artifacts never enter the caller's conversation. Use when the caller wants the ${noun} rather than the working. Do NOT use when the user wants to see or steer each step (run the /${name} command inline instead), or for a job one method answers (use that skill).
tools: ${AGENT_TOOLS}
skills:
${skillsYaml}
---
<!-- GENERATED by ${GENERATED_BY} from _workflows/${name}.md - do not edit. Regenerate: npm run gen:recipe-commands -->

You are the **${name}** delegate. You run the ${n}-skill ${name} recipe from start to finish in your own context and hand back only its final artifact, ${artifact}. The caller delegated to you so that the intermediate artifacts would stay out of its conversation; returning them defeats the point.

The chain's ${n} skills are preloaded into your context: ${skillsList}. Each one points at its own \`references/TEMPLATE.md\` (the structure its artifact follows) and \`references/EXAMPLE.md\` (the quality anchor). Open both with Read, from that skill's base directory, before producing its step.

## The chain

${authored}

## How to run it

- You start without the caller's conversation. Everything you know is in the delegation message and any files it names. Where a step needs something the message does not supply, state the assumption inside the artifact rather than inventing a fact.
- Run every step, in order, even though you return only the last. Carry forward exactly what each handoff names and nothing more.
- Run only the preloaded skills. If the chain above names an optional add or a swap-in, do not run it; if the situation clearly warrants one, name it and why in one line after the artifact, so the caller can run it.
- Each preloaded skill's own rules still bind, including its "When NOT to Use". If a step's procedure says it does not fit this situation, stop and return that finding instead of a forced artifact.

## What to return

Return ${artifact}, assembled from what each handoff carried forward, and nothing else: no step-by-step narration and no intermediate artifacts. The composite-artifact line above names what it must contain. You may close with one line naming the files you read.

## Tool constraints (hard limits)

You are granted three tools, Read, Glob and Grep, and all three are read-only. That is deliberate.

- They serve exactly three purposes: opening the preloaded skills' \`references/\` files, reading the recipe's own prose that the chain above points to, and reading material the delegation message points you to.
- You write nothing: no file, no edit, no command. The artifact is your response.
- If a step appears to need more than this (a web search, running code, writing a file), that is a finding, not a licence. Say what was needed and why, then continue without it or stop.
`;
}

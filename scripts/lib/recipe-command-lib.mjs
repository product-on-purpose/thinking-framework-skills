// =============================================================================
// recipe-command-lib.mjs - rendering a recipe into an invokable slash command, as a pure lib.
//
// what-it-is:   the transform from a _workflows/<name>.md recipe to a commands/<name>.md command.
// what-it-does: renderCommand(name, recipeMarkdown) -> the exact command file contents.
// why:          SPEC-09 phase 1b. Kept separate from the CLI because the CLI reads and WRITES
//               files at module scope; a test importing it would run the generator as a side
//               effect and exit the process. Same split as cases-lib / lifecycle-lib: pure rules
//               here, thin executable there.
// used-by:      scripts/gen-recipe-commands.mjs; tests/gen-recipe-commands.test.mjs
//
// The recipe BODY is carried verbatim rather than reconstructed from `steps:`. The numbered
// handoff lines ("-> carry the **chosen working frame**") are the authored value of a recipe: the
// compression at each step is what makes a chain cheaper than running the skills back to back.
// Rebuilding that from the steps array would silently drop it, along with the framing paragraphs
// and the "optional adds when stakes justify the tokens" lines some recipes carry.
// =============================================================================

export const ARGUMENT_HINT = '[the decision, problem, or material to work through]';

function frontmatterBlock(md) {
  const m = String(md || '').match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  return m ? { fm: m[1], body: m[2] } : { fm: '', body: String(md || '') };
}

/** Flat scalar out of the recipe frontmatter. Recipes author `description:` on one line. */
function scalar(fm, key) {
  const m = fm.match(new RegExp(`^${key}:\\s*(.+?)\\s*$`, 'm'));
  return m ? m[1].replace(/^['"]|['"]$/g, '').trim() : null;
}

/** How many skills the chain runs, from the authored steps list rather than by counting prose. */
export function stepCount(fm) {
  const m = String(fm || '').match(/^steps:\s*$([\s\S]*?)(?=^\S|\Z)/m);
  if (!m) return 0;
  return (m[1].match(/^\s*-\s+\S+/gm) || []).length;
}

/**
 * Everything after the H1 title line: the framing, the run-in-order instruction, the numbered
 * handoff chain, any optional adds, and the composite-artifact line. The title itself is dropped
 * because the command supplies its own opening.
 */
export function bodyAfterTitle(body) {
  const lines = String(body || '').split(/\r?\n/);
  const i = lines.findIndex((l) => /^#\s+/.test(l));
  return (i === -1 ? lines : lines.slice(i + 1)).join('\n').trim();
}

/** Render one recipe into its command file contents. Deterministic: same input, same bytes. */
export function renderCommand(name, recipeMd) {
  const { fm, body } = frontmatterBlock(recipeMd);
  const description = scalar(fm, 'description') || '';
  const n = stepCount(fm);
  const authored = bodyAfterTitle(body);
  return `---
description: ${description}
argument-hint: "${ARGUMENT_HINT}"
maps-to: ${name}
---
<!-- GENERATED by scripts/gen-recipe-commands.mjs from _workflows/${name}.md - do not edit. Regenerate: npm run gen:recipe-commands -->

Run the **${name}** recipe: ${n} skills chained in a fixed order, carrying forward only the compressed artifact at each handoff.

The compression is the point. Do not paste a whole artifact into the next step; carry exactly what each handoff names, so the chain stays cheaper and sharper than running the skills back to back.

${authored}

Apply the chain to: $ARGUMENTS
`;
}

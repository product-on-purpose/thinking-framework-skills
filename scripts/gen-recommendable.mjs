#!/usr/bin/env node
// gen-recommendable.mjs - generate the name-safety "recommendable set" for think-framework-advisor.
//
// WHY THIS EXISTS: the advisor is a router; its one unacceptable failure is naming a skill
// that does not exist. This script derives the set of valid, recommendable component names
// from the registration source of truth (library.json) joined with each skill's own SKILL.md
// frontmatter (family, evidence-tier, id, description) and the workflow recipes (_workflows/*.md).
// Re-run it whenever skills or recipes are added/removed so the advisor's name set never drifts.
//
// OUTPUT (written into the advisor skill so it travels with it):
//   skills/think-framework-advisor/references/recommendable.json   (machine: the authoritative set)
//   skills/think-framework-advisor/references/recommendable.md      (human: a readable table)
//
// Usage:  node scripts/gen-recommendable.mjs        (from the repo root)
//         node scripts/gen-recommendable.mjs --check (exit 1 if output would change; for CI)
//
// No dependencies. Reads/writes UTF-8 explicitly (Windows cp1252 would otherwise corrupt).

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const OUT_DIR = join(ROOT, 'skills', 'think-framework-advisor', 'references');

// --- tiny, tolerant frontmatter reader (no YAML dependency) ---------------
// Handles the controlled shape these files actually use: top-level `key: value`,
// one level of nesting under `metadata:`, and `steps:` as a list of `- item`.
function readFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const lines = m[1].split(/\r?\n/);
  const out = {};
  let parentKey = null;
  let listKey = null;
  for (const raw of lines) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    const indent = raw.length - raw.replace(/^\s+/, '').length;
    const line = raw.trim();
    if (line.startsWith('- ')) {
      // list item belongs to the most recently seen `key:` with no value
      if (listKey) (out[listKey] ||= []).push(stripQuotes(line.slice(2).trim()));
      continue;
    }
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    const [, key, value] = kv;
    if (indent === 0) {
      parentKey = null;
      if (value === '') { listKey = key; out[key] = out[key] ?? null; }
      else { listKey = null; out[key] = stripQuotes(value); }
      if (key === 'metadata' && value === '') { parentKey = 'metadata'; out.metadata = {}; }
    } else if (parentKey === 'metadata') {
      if (value !== '') out.metadata[key] = stripQuotes(value);
    }
  }
  return out;
}
function stripQuotes(s) {
  return s.replace(/^["']/, '').replace(/["']$/, '').trim();
}

// --- gather skills from library.json (the registration source of truth) ----
const lib = JSON.parse(readFileSync(join(ROOT, 'library.json'), 'utf8'));
const skills = [];
for (const c of lib.components.skills) {
  if (c.name === 'think-framework-advisor') continue; // the advisor never recommends itself
  const fm = readFrontmatter(readFileSync(join(ROOT, c.path), 'utf8'));
  const meta = fm.metadata || {};
  skills.push({
    name: fm.name || c.name,
    id: meta.id || null,
    family: meta.family || null,
    tier: meta['evidence-tier'] || null,
    description: fm.description || '',
  });
}
skills.sort((a, b) => a.name.localeCompare(b.name));

// --- gather recipes from _workflows/*.md ------------------------------------
const wfDir = join(ROOT, '_workflows');
const recipes = [];
if (existsSync(wfDir)) {
  for (const f of readdirSync(wfDir).filter((f) => f.endsWith('.md')).sort()) {
    const fm = readFrontmatter(readFileSync(join(wfDir, f), 'utf8'));
    const slug = (fm.name || f.replace(/\.md$/, '')).replace(/^think-/, '');
    recipes.push({
      name: fm.name || f.replace(/\.md$/, ''),
      slug,
      recipe_doc: `recipes/${slug}.md`,
      description: fm.description || '',
      steps: fm.steps || [],
    });
  }
}

// --- emit -------------------------------------------------------------------
const data = {
  $note: 'GENERATED by scripts/gen-recommendable.mjs - do not hand-edit. The name-safety set think-framework-advisor recommends from. Regenerate when components change.',
  generated_from: 'library.json + skills/*/SKILL.md frontmatter + _workflows/*.md',
  skill_count: skills.length,
  recipe_count: recipes.length,
  skills,
  recipes,
};

const json = JSON.stringify(data, null, 2) + '\n';

const md = renderMd(skills, recipes);

if (process.argv.includes('--check')) {
  const cur = existsSync(join(OUT_DIR, 'recommendable.json'))
    ? readFileSync(join(OUT_DIR, 'recommendable.json'), 'utf8')
    : '';
  if (cur !== json) {
    console.error('recommendable.json is stale - run: node scripts/gen-recommendable.mjs');
    process.exit(1);
  }
  console.log('recommendable set is up to date.');
  process.exit(0);
}

writeFileSync(join(OUT_DIR, 'recommendable.json'), json, 'utf8');
writeFileSync(join(OUT_DIR, 'recommendable.md'), md, 'utf8');
console.log(`Wrote ${skills.length} skills + ${recipes.length} recipes to ${OUT_DIR}`);

function renderMd(skills, recipes) {
  const L = [];
  L.push('# Recommendable set (generated)');
  L.push('');
  L.push('> GENERATED by `scripts/gen-recommendable.mjs` - do not hand-edit.');
  L.push('> This is the **only** set of names `think-framework-advisor` may recommend. If a');
  L.push('> component is not listed here, the advisor must describe the step in plain language');
  L.push('> rather than name a skill. Regenerate when components change.');
  L.push('');
  L.push(`## Skills (${skills.length})`);
  L.push('');
  L.push('| Skill (`name`) | Family | Tier | What it does |');
  L.push('|---|---|---|---|');
  for (const s of skills) {
    const oneLine = s.description.replace(/\s+/g, ' ').replace(/\|/g, '\\|');
    const useWhen = oneLine.split(/\.\s/)[0] + '.';
    L.push(`| \`${s.name}\` | ${s.family || '-'} | ${s.tier || '-'} | ${truncate(useWhen, 160)} |`);
  }
  L.push('');
  L.push(`## Recipes (${recipes.length})`);
  L.push('');
  L.push('Multi-step chains. Recommend the recipe (by name) when the job needs the whole sequence; the steps are the skills it runs in order.');
  L.push('');
  L.push('| Recipe (`name`) | Prose | Steps |');
  L.push('|---|---|---|');
  for (const r of recipes) {
    L.push(`| \`${r.name}\` | \`${r.recipe_doc}\` | ${r.steps.map((s) => `\`${s}\``).join(' -> ')} |`);
  }
  L.push('');
  return L.join('\n');
}
function truncate(s, n) {
  return s.length > n ? s.slice(0, n - 1).trimEnd() + '...' : s;
}
